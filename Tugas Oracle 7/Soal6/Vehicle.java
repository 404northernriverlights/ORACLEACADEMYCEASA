package Soal6;

public class Vehicle {
    private int wheels;
    private int numSeats;

    public Vehicle(int wheels, int numSeats) {
        this.wheels = wheels;
        this.numSeats = numSeats;
    }

    public int getWheels() {
        return wheels;
    }

    public int getNumSeats() {
        return numSeats;
    }
}