public class GabungString {
    public static void main(String[] args) {
        // Mendeklarasikan dan menginstansiasi dua string terpisah
        String bagianPertama = "Belajar ";
        String bagianKedua = "Java";
        
        // Menggabungkan keduanya dan menetapkan ke object String ketiga
        String resultString = bagianPertama + bagianKedua;
        
        // Menampilkan hasil
        System.out.println(resultString); 
    }
}